# 문제 2
# 이름: 민수, 지수, 철수, 영희, 수진
# 나이: 20, 21, 20, 22, 21
# 점수: 75, 90, 85, 60, 95

# DataFrame 만들기
import pandas as pd

data = {
    "이름" : ["민수", "지수", "철수", "영희", "수진"],
    "나이" : [20, 21, 20, 22, 21],
    "점수" : [75, 90, 85, 60, 95]
}

df = pd.DataFrame(data)

print(df)

# 점수가 80점 이상인 사람의 이름만 출력
print(df[df["점수"] >= 80]["이름"])
# 1    지수
# 2    철수
# 4    수진

# 나이가 21살인 사람만 출력
print(df[df["나이"] == 21])
#    이름  나이  점수
# 1  지수  21  90
# 4  수진  21  95

# "등급"이라는 새 열 만들기 - apply()
#  90점 이상 -> A, 80점 이상 -> B, 나머지 -> C
def get_grade(score):
    if score >= 90:
        return "A"
    elif score >= 80:
        return "B"
    else:
        return "C"

df["등급"] = df["점수"].apply(get_grade)   # 점수 하나하나를 get_grade()에 넣어서 결과를 새로운 열로 만드는 것
#    이름  나이  점수 등급
# 0  민수  20  75  C
# 1  지수  21  90  A
# 2  철수  20  85  B
# 3  영희  22  60  C
# 4  수진  21  95  A

# 등급이 "A"인 사람만 출력
print(df[df["등급"] == "A"])
#    이름  나이  점수 등급
# 1  지수  21  90  A
# 4  수진  21  95  A