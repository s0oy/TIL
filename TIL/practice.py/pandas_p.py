# 1. Pandas?
# 표 형태의 데이터를 다루는 구조

# 2. Pandas 불러오기
# pd는 Pandas의 별명
import pandas as pd

# 3. DataFrame 만들기
# Pandas의 가장 중요한 자료형이 DataFrame
# DataFrame
#  ├── 행(row)
#  └── 열(column)
import pandas as pd

data = {
    "이름" : ["민수", "지수", "철수"],
    "나이" : [20, 21, 20],
    "점수" : [80, 90, 75]
}

df = pd.DataFrame(data)

print(df) 
#    이름  나이  점수
# 0  민수  20  80
# 1  지수  21  90
# 2  철수  20  75

# 4. 특정 열 가져오기
print(df["점수"])
# 0    80
# 1    90
# 2    75

# 여러 열도 가능
print(df["이름", "점수"])

# 5. 평균 구하기
# NumPy에서 했던것처럼 Pandas에서도 바로 계산 가능
print(df["점수"].mean())   # 81.66666666666667

print(df["점수"].max())    # 최댓값
print(df["점수"].min())    # 최솟값

# 6. 조건으로 데이터 찾기
# 점수가 80점 이상인 사람만 찾고 싶다면
print(df[df["점수"] >= 80]) 
#   이름  나이  점수
# 0  민수  20  80
# 1  지수  21  90

# 구조를 보면
df["점수"] >= 80

# 먼저 조건을 만들고 df[조건]["가져올 열"]으로 해당 행만 가져오는 것

# 7. 조건 여러 개
# 예를 들어 나이가 20살이고 점수가 80점 이상인 사람
print(df[(df["나이"] == 20) & (df["점수"] >= 80)])

# 주의
# & -> AND
# | -> OR

# 8. 새로운 열 만들기
# 데이터 전처리 시 많이 사용됨
# 예를 들어 80점 이상이면 합격이라고 했을 때
df["합격"] = df["점수"] >= 80

print(df)
#    이름  나이  점수  합격
# 0  민수  20   80   True
# 1  지수  21   90   True
# 2  철수  20   75   False

# 9. 정렬
# 점수가 높은 순서
print(df.sort_values("점수", ascending=False))  # ascending=False -> 내림차순

# 낮은 순서
print(df.sort_values("점수"))   # ascending=True -> 오름차순

# 10. 데이터 기본 정보 확인
# 숫자 데이터의 개수, 평균, 표준편차, 최솟값, 25%, 50%, 75%, 최댓값 등을 한번에 볼 수 있음
print(df.describe())

# 정리
df["점수"] >= 80              # 조건을 만든다
df[df["점수"] >= 80]          # 조건에 맞는 행을 가져온다
df[df["점수"] >= 80]["이름"]   # 조건에 맞는 행에서 이름만 가져온다

